#!/bin/bash
# TPS Dataset Auto-Organization Script
# Automatically organizes TPS preprocessing outputs into dated, structured dataset

set -e

# Get current date
DATE=$(date +%Y%m%d)
DATASET_NAME="TPS_Dataset_${DATE}"
BASE_DIR="/data/gpfs/projects/punim2657/sfs_preprocessing"
DATASET_DIR="${BASE_DIR}/${DATASET_NAME}"

echo "=== TPS Dataset Auto-Organization ==="
echo "Dataset: ${DATASET_NAME}"
echo "Location: ${DATASET_DIR}"
echo

# Create organized dataset structure matching original samples
mkdir -p "${DATASET_DIR}/SfS_pp"/{Surfaces,Axes,Breaklines,Mesh}

echo "Created dataset structure:"
echo "  ${DATASET_DIR}/SfS_pp/"
echo "    ├── Surfaces/"
echo "    ├── Axes/"
echo "    ├── Breaklines/"
echo "    └── Mesh/"
echo

# Copy TPS surfaces
if [ -d "${BASE_DIR}/Surfaces" ] && [ "$(ls -A ${BASE_DIR}/Surfaces/*.xyz 2>/dev/null)" ]; then
    cp "${BASE_DIR}/Surfaces"/*.xyz "${DATASET_DIR}/SfS_pp/Surfaces/"
    echo "✅ Copied TPS surfaces ($(ls ${BASE_DIR}/Surfaces/*.xyz | wc -l) files)"
else
    echo "❌ Warning: No TPS surfaces found in ${BASE_DIR}/Surfaces/"
fi

# Copy TPS axes
if [ -d "${BASE_DIR}/TPS_Output/Axes" ] && [ "$(ls -A ${BASE_DIR}/TPS_Output/Axes/*.xyz 2>/dev/null)" ]; then
    cp "${BASE_DIR}/TPS_Output/Axes"/*.xyz "${DATASET_DIR}/SfS_pp/Axes/"
    echo "✅ Copied TPS axes ($(ls ${BASE_DIR}/TPS_Output/Axes/*.xyz | wc -l) files)"
else
    echo "❌ Warning: No TPS axes found in ${BASE_DIR}/TPS_Output/Axes/"
fi

# Copy mesh files
if [ -d "${BASE_DIR}/Dataset/Mesh/Pot_A" ] && [ "$(ls -A ${BASE_DIR}/Dataset/Mesh/Pot_A/*.obj 2>/dev/null)" ]; then
    cp "${BASE_DIR}/Dataset/Mesh/Pot_A"/*.obj "${DATASET_DIR}/SfS_pp/Mesh/"
    echo "✅ Copied mesh files ($(ls ${BASE_DIR}/Dataset/Mesh/Pot_A/*.obj | wc -l) files)"
else
    echo "❌ Warning: No mesh files found in ${BASE_DIR}/Dataset/Mesh/Pot_A/"
fi

# Copy Surface_F files
SURFACE_F_COUNT=0
if [ "$(ls -A ${BASE_DIR}/*Surface_F.pcd 2>/dev/null)" ]; then
    cp "${BASE_DIR}"/*Surface_F.pcd "${DATASET_DIR}/SfS_pp/Surfaces/"
    SURFACE_F_COUNT=$((SURFACE_F_COUNT + $(ls ${BASE_DIR}/*Surface_F.pcd | wc -l)))
fi
if [ -d "${BASE_DIR}/TPS_Surface_F_XYZ" ] && [ "$(ls -A ${BASE_DIR}/TPS_Surface_F_XYZ/*.xyz 2>/dev/null)" ]; then
    cp "${BASE_DIR}/TPS_Surface_F_XYZ"/*.xyz "${DATASET_DIR}/SfS_pp/Surfaces/"
    SURFACE_F_COUNT=$((SURFACE_F_COUNT + $(ls ${BASE_DIR}/TPS_Surface_F_XYZ/*.xyz | wc -l)))
fi

if [ $SURFACE_F_COUNT -gt 0 ]; then
    echo "✅ Copied Surface_F files ($SURFACE_F_COUNT files)"
else
    echo "❌ Warning: No Surface_F files found"
fi

# Document missing breaklines
cat > "${DATASET_DIR}/SfS_pp/Breaklines/README.md" << EOF
# TPS Breaklines - Missing

**Status**: Not generated by TPS preprocessing pipeline
**Issue**: TPS-compatible breaklines need to be generated from mesh/surface data
**Impact**: Using NURBS breaklines causes geometric mismatch in SFS feature matching

**To Generate**: 
1. Implement TPS breakline extraction from mesh edges
2. Or adapt existing breakline generation for TPS surface geometry

**Current Workaround**: Cannot use this dataset for SFS testing until breaklines are available
EOF

echo "📝 Documented missing breaklines in README.md"

# Create dataset documentation
cat > "${DATASET_DIR}/README.md" << EOF
# TPS Preprocessing Dataset - $(date +"%B %d, %Y")

**Pipeline Type**: TPS (Thin Plate Spline) Surface Fitting  
**Generated**: $(date)  
**Pottery Collection**: Pot A (8 pieces)  
**Auto-organized**: Yes (organize_dataset.sh)

## Dataset Structure:
Matches original sample organization for compatibility:
\`\`\`
${DATASET_NAME}/
└── SfS_pp/
    ├── Surfaces/     # TPS-fitted surfaces + Surface_F files
    ├── Axes/         # MATLAB PotSAC extracted axes  
    ├── Breaklines/   # ❌ MISSING - needs TPS-specific generation
    └── Mesh/         # Original OBJ mesh files
\`\`\`

## File Inventory:
- **Surfaces**: $(ls ${DATASET_DIR}/SfS_pp/Surfaces/*.xyz 2>/dev/null | wc -l) surface files
- **Surface_F**: $(ls ${DATASET_DIR}/SfS_pp/Surfaces/*Surface_F.* 2>/dev/null | wc -l) feature files  
- **Axes**: $(ls ${DATASET_DIR}/SfS_pp/Axes/*.xyz 2>/dev/null | wc -l) axis files
- **Mesh**: $(ls ${DATASET_DIR}/SfS_pp/Mesh/*.obj 2>/dev/null | wc -l) mesh files
- **Breaklines**: 0 files (missing)

## Usage:
\`\`\`bash
# Replace main SFS dataset with TPS version
cp -r ${DATASET_NAME}/SfS_pp/* /path/to/sfs_main/sfspreproc-docker/Dataset/SfS_pp/
\`\`\`

## Comparison to Original NURBS Dataset:
- **Original**: \`/data/gpfs/projects/punim2657/sfs_main/original_samples/SfS_pp/\`
- **TPS Version**: \`${DATASET_DIR}/SfS_pp/\`

**Status**: Dataset ready except for missing breaklines
EOF

echo "📋 Created dataset documentation: ${DATASET_DIR}/README.md"

# Display summary
echo
echo "=== Dataset Organization Complete ==="
echo "📁 Location: ${DATASET_DIR}"
echo "📊 Components:"
echo "   ✅ Surfaces: $(ls ${DATASET_DIR}/SfS_pp/Surfaces/*.xyz 2>/dev/null | wc -l) files"
echo "   ✅ Axes: $(ls ${DATASET_DIR}/SfS_pp/Axes/*.xyz 2>/dev/null | wc -l) files"
echo "   ✅ Mesh: $(ls ${DATASET_DIR}/SfS_pp/Mesh/*.obj 2>/dev/null | wc -l) files"
echo "   ✅ Surface_F: $(ls ${DATASET_DIR}/SfS_pp/Surfaces/*Surface_F.* 2>/dev/null | wc -l) files"
echo "   ❌ Breaklines: 0 files (missing)"
echo
echo "🎯 Next Steps:"
echo "   1. Generate TPS-compatible breaklines"
echo "   2. Copy to SFS main: cp -r ${DATASET_NAME}/SfS_pp/* sfspreproc-docker/Dataset/SfS_pp/"
echo

# Create symlink to latest dataset
ln -sfn "${DATASET_NAME}" "${BASE_DIR}/latest_tps_dataset"
echo "🔗 Created symlink: ${BASE_DIR}/latest_tps_dataset -> ${DATASET_NAME}"